export function iconForText(text: string): string | undefined {
  for (const [re, icon] of RULES) if (re.test(text)) return icon;
  return undefined;
}

export function iconForField(f: Field, v: Values): string | undefined {
  if (f.icon) return f.icon;
  const stat = typeof f.stat === 'function' ? f.stat(v) : f.stat;
  const key = f.statArray?.[0] ?? stat;
  if (key && STAT_ICONS[key]) return STAT_ICONS[key];
  return iconForText(f.label);
}
